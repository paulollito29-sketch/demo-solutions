export function getThemeForRubro(rubro: string): RubroTheme {
  if (RUBRO_THEMES[rubro]) return RUBRO_THEMES[rubro];
  if (rubro.toLowerCase().includes("clínica") || rubro.toLowerCase().includes("clinica")) return RUBRO_THEMES["Clínica y terapia"];
  if (rubro.toLowerCase().includes("restaurante") || rubro.toLowerCase().includes("cevich")) return RUBRO_THEMES["Restaurante y cafetería"];
  if (rubro.toLowerCase().includes("dental") || rubro.toLowerCase().includes("odont")) return RUBRO_THEMES["Odontología"];
  if (rubro.toLowerCase().includes("veterinaria") || rubro.toLowerCase().includes("pet")) return RUBRO_THEMES["Veterinaria"];
  if (rubro.toLowerCase().includes("hotel") || rubro.toLowerCase().includes("hospedaje")) return RUBRO_THEMES["Hospedaje"];
  if (rubro.toLowerCase().includes("comercio") || rubro.toLowerCase().includes("tienda")) return RUBRO_THEMES["Comercio especializado"];
  if (rubro.toLowerCase().includes("nido") || rubro.toLowerCase().includes("educa")) return RUBRO_THEMES["Educación privada"];
  return RUBRO_THEMES["Belleza y bienestar"];
}
